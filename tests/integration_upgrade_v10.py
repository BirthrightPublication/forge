def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--base', type=Path, required=True, help='Manifest-verified V0.9 source release ZIP.')
    parser.add_argument('--build', type=Path, required=True, help='Manifest-verified V0.10 source release ZIP.')
    parser.add_argument('--output', type=Path, required=True, help='NEW disposable directory outside any installation.')
    parser.add_argument('--base-commit', default='', help='Exact approved V0.9 source commit, recorded as supplied provenance.')
    parser.add_argument('--allow-test-writes', action='store_true')
    args = parser.parse_args(argv)
    if not args.allow_test_writes:
        parser.error('Pass --allow-test-writes only for a NEW disposable directory.')
    home = args.output.resolve()
    if home.exists():
        raise RuntimeError('The disposable directory already exists; existing installations are never reused.')
    if any((parent / 'VERSION.txt').is_file() and (parent / 'forge/app.py').is_file() for parent in home.parents):
        raise RuntimeError('Keep the disposable test outside every existing FORGE source/installation.')
    base, candidate = args.base.resolve(), args.build.resolve()
